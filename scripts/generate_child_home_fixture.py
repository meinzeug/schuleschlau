#!/usr/bin/env python3
"""Generate a browser-readable test fixture from the canonical synthetic JSON.

Run with --check in CI to reject a stale generated Dart fixture.
"""
from __future__ import annotations

import argparse
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'app/test/fixtures/child_home.json'
TARGET = ROOT / 'app/test/fixtures/child_home_encoded.dart'


def generated() -> str:
    encoded = base64.b64encode(SOURCE.read_bytes()).decode('ascii')
    chunks = [encoded[i:i + 76] for i in range(0, len(encoded), 76)]
    return (
        '// Generated from child_home.json by scripts/generate_child_home_fixture.py.\n'
        '// Do not edit this file directly.\n'
        'const syntheticChildHomeBase64 =\n'
        + ''.join(f"    '{chunk}'\n" for chunk in chunks[:-1])
        + f"    '{chunks[-1]}';\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected:
            print('Generated child-home fixture is stale; run scripts/generate_child_home_fixture.py')
            return 1
    else:
        TARGET.write_text(expected, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
